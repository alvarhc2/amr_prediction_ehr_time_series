def clinical_name(feature: str) -> str:
    """Return the English label used in the paper when one exists."""
    return CLINICAL_ALIASES.get(feature, feature)


def feature_group(feature: str) -> str:
    """Map a column to the feature set described in the paper."""
    if feature in {"day_week", "day_month", "month"}:
        return "temporal"
    if feature.startswith("icu_"):
        if feature == "icu_mechanic_ventilation" or feature.startswith("icu_antibiotics-"):
            return "icu_treatment"
        if feature == "icu_pseudomonas_aeruginosa_detected" or feature.startswith("icu_resistance_"):
            return "icu_resistance"
        return "icu_admission"
    if feature == "related_patients":
        return "coadmitted"
    if feature == "mechanic_ventilation" or feature.startswith("antibiotics-"):
        return "treatment"
    if feature == "pseudomonas_aeruginosa_detected" or feature.startswith("resistance_"):
        return "resistance"
    if feature == "cultures" or feature.startswith(("culture_", "antibiogram_")):
        return "culture"
    if (
        feature in {"admission", "age", "gender"}
        or feature.startswith(("origin-", "destination-", "reason_admission-", "patient_category-"))
    ):
        return "admission"
    raise KeyError(feature)


def group_counts(names: tuple[str, ...] | list[str] | None = None) -> dict[str, int]:
    """Count columns in each feature set."""
    chosen = FEATURES if names is None else names
    counts = {group: 0 for group in GROUPS}
    for name in chosen:
        counts[feature_group(name)] += 1
    return counts
